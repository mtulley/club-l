CREATE TABLE IF NOT EXISTS stripe_webhook_events (
  event_id TEXT PRIMARY KEY,
  event_type TEXT NOT NULL,
  processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS shop_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stripe_checkout_session_id TEXT NOT NULL UNIQUE,
  stripe_payment_intent_id TEXT UNIQUE,
  customer_email TEXT,
  shipping_address JSONB,
  fulfillment_status TEXT NOT NULL DEFAULT 'unfulfilled'
    CHECK (fulfillment_status IN ('unfulfilled', 'needs_review', 'fulfilled')),
  currency CHAR(3) NOT NULL CHECK (currency ~ '^[a-z]{3}$'),
  amount_subtotal INTEGER NOT NULL CHECK (amount_subtotal >= 0),
  amount_tax INTEGER NOT NULL DEFAULT 0 CHECK (amount_tax >= 0),
  amount_shipping INTEGER NOT NULL DEFAULT 0 CHECK (amount_shipping >= 0),
  amount_total INTEGER NOT NULL CHECK (amount_total >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS shop_orders_created_at_idx
  ON shop_orders (created_at DESC);

CREATE TABLE IF NOT EXISTS shop_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES shop_orders (id) ON DELETE CASCADE,
  stripe_line_item_id TEXT NOT NULL UNIQUE,
  product_id TEXT,
  product_name TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10),
  unit_amount INTEGER NOT NULL CHECK (unit_amount BETWEEN 1 AND 99999999),
  line_total INTEGER NOT NULL CHECK (line_total >= 0)
);

CREATE INDEX IF NOT EXISTS shop_order_items_order_id_idx
  ON shop_order_items (order_id);
